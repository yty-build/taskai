// ABOUTME: Verifies that concurrent Claude mirror shutdown callers share one completed boundary.
// ABOUTME: Uses a paused handler and private fixture sockets, without contacting a native provider.

use std::{
    io::{Read, Write},
    os::unix::net::UnixStream,
    sync::{
        atomic::{AtomicUsize, Ordering},
        mpsc::{self, Receiver, Sender},
        Arc, Mutex,
    },
    time::{Duration, Instant},
};

use serde_json::{json, Value};
use taskai_connectors::claude::{
    drift::Drift,
    envelope::Envelope,
    mirror::{DoorHandler, Mirror, MirrorConfig},
};
use taskai_core::{
    mail::{Frame, PermissionMode},
    sha256_hex,
};

struct PausedHandler {
    entered: Sender<()>,
    release: Mutex<Receiver<()>>,
    accepted: AtomicUsize,
}

impl DoorHandler for PausedHandler {
    fn sender(&self, _from: &str) -> Option<String> {
        self.entered.send(()).unwrap();
        // A failed test must not strand the listener's handler forever.
        let _ = self
            .release
            .lock()
            .unwrap()
            .recv_timeout(Duration::from_secs(5));
        Some("claude-sender".into())
    }

    fn accept(&self, _frame: Frame) {
        self.accepted.fetch_add(1, Ordering::SeqCst);
    }

    fn refuse(&self, _reason: &str) {}
}

fn connection_ended(stream: &mut UnixStream) -> bool {
    stream.set_nonblocking(true).unwrap();
    let deadline = Instant::now() + Duration::from_secs(2);
    loop {
        match stream.read(&mut [0; 1]) {
            Ok(0) => return true,
            Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {}
            Err(error) if error.kind() == std::io::ErrorKind::ConnectionReset => return true,
            _ => return false,
        }
        if Instant::now() >= deadline {
            return false;
        }
        std::thread::sleep(Duration::from_millis(5));
    }
}

// Expectation: every concurrent close waits for the in-hand frame and owned-file cleanup.
// Why: a second shutdown path must not interpret "closing" as "closed" and tear down the
// handler's dependencies while a frame is still running. Value: one reliable completion boundary.
#[test]
fn every_close_waits_for_admission_to_drain() {
    let root = tempfile::Builder::new()
        .prefix("mc.")
        .tempdir_in("/tmp")
        .unwrap();
    let sessions = root.path().join("sessions");
    let sockets = root.path().join("sockets");
    let pid = std::process::id();
    let door = sockets.join(format!("{pid}.sock"));
    let key = sessions.join(format!(
        "{pid}.{}.key",
        sha256_hex(door.to_str().unwrap().as_bytes())
    ));
    let card = sessions.join(format!("{pid}.json"));
    let (entered_tx, entered_rx) = mpsc::channel();
    let (release_tx, release_rx) = mpsc::channel();
    let handler = Arc::new(PausedHandler {
        entered: entered_tx,
        release: Mutex::new(release_rx),
        accepted: AtomicUsize::new(0),
    });
    let mirror = Arc::new(
        Mirror::prepare(
            MirrorConfig {
                sessions_dir: sessions,
                socket_dir: sockets,
                name: "codex-receiver".into(),
                harness: "codex".into(),
                session_id: "fixture-thread".into(),
                cwd: root.path().into(),
            },
            &Drift {
                enabled: true,
                reasons: Vec::new(),
            },
        )
        .unwrap()
        .publish(handler.clone())
        .unwrap(),
    );
    // This is the key generated by this private fixture, never a provider-owned key.
    let fixture_key: Value = serde_json::from_slice(&std::fs::read(&key).unwrap()).unwrap();
    let mut stream = UnixStream::connect(&door).unwrap();
    writeln!(
        stream,
        "{}",
        json!({"type":"auth", "token":fixture_key["peerToken"]})
    )
    .unwrap();
    let from = "uds:/tmp/cc-socks/fixture-sender.sock";
    let content = Envelope {
        from: Some(from.into()),
        from_name: Some("claude-sender".into()),
        from_mode: Some(PermissionMode::Prompting),
        body: "fixture letter".into(),
        ..Envelope::default()
    }
    .render();
    writeln!(
        stream,
        "{}",
        json!({"msgV":1,"type":"user","msg_id":"fixture-letter",
        "priority":"next","from":from,"message":{"role":"user","content":content}})
    )
    .unwrap();
    entered_rx.recv_timeout(Duration::from_secs(2)).unwrap();
    let first_mirror = mirror.clone();
    let first = std::thread::spawn(move || first_mirror.close());
    // The first close has shut accepted streams and is now draining this paused handler.
    assert!(connection_ended(&mut stream));

    let (second_started_tx, second_started_rx) = mpsc::channel();
    let (second_done_tx, second_done_rx) = mpsc::channel();
    let second_mirror = mirror.clone();
    let second = std::thread::spawn(move || {
        second_started_tx.send(()).unwrap();
        second_mirror.close();
        second_done_tx.send(()).unwrap();
    });
    second_started_rx
        .recv_timeout(Duration::from_secs(2))
        .unwrap();
    let returned_before_drain = second_done_rx
        .recv_timeout(Duration::from_millis(200))
        .is_ok();
    // Release and join both callers before asserting, including on the expected red run.
    release_tx.send(()).unwrap();
    first.join().unwrap();
    second.join().unwrap();
    assert!(
        !returned_before_drain,
        "a concurrent close returned while a handler was still in flight"
    );
    assert_eq!(handler.accepted.load(Ordering::SeqCst), 1);
    assert!(!door.exists() && !key.exists() && !card.exists());
    mirror.close();
}
